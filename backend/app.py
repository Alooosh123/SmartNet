async def run_sqlite_migrations(conn) -> None:
    """Small compatibility migration for existing local SQLite installations.

    Production schema evolution is managed by Alembic (alembic upgrade head).
    """
    if conn.dialect.name != "sqlite":
        return

    migrations = {
        "registration_requests": {
            "plan": "VARCHAR DEFAULT 'monthly'",
            "price": "INTEGER DEFAULT 20",
            "receipt_image": "VARCHAR",
            "registration_token_hash": "VARCHAR",
        },
        "clients": {
            "plan": "VARCHAR DEFAULT 'monthly'",
            "can_reboot_network": "BOOLEAN DEFAULT 0",
        },
        "card_batches": {
            "owner_username": "VARCHAR",
        },
    }
    for table, columns in migrations.items():
        rows = await conn.execute(text(f"PRAGMA table_info({table})"))
        existing = {row[1] for row in rows.fetchall()}
        for name, definition in columns.items():
            if name not in existing:
                await conn.execute(text(f"ALTER TABLE {table} ADD COLUMN {name} {definition}"))


async def migrate_legacy_public_pdfs(session) -> None:
    """Move older credential PDFs out of the publicly mounted static directory.

    Existing databases may reference files generated by earlier SmartNet versions
    under backend/static/pdfs. Startup moves those files to private uploads storage
    and updates their paths before serving HTTP requests.
    """
    backend_root = Path(__file__).resolve().parent
    public_pdf_dir = (backend_root / "static" / "pdfs").resolve()
    private_pdf_dir = (backend_root / "uploads" / "pdfs").resolve()
    public_pdf_dir.mkdir(parents=True, exist_ok=True)
    private_pdf_dir.mkdir(parents=True, exist_ok=True)

    moved_by_name = {}
    for source in public_pdf_dir.glob("*.pdf"):
        destination = private_pdf_dir / source.name
        try:
            if destination.exists():
                source.unlink()
            else:
                shutil.move(str(source), str(destination))
            moved_by_name[source.name] = destination
        except OSError:
            logger.exception("Could not secure legacy public PDF: %s", source)
            raise

    if not moved_by_name:
        return

    result = await session.execute(select(models.CardBatch))
    batches = result.scalars().all()
    changed = False
    for batch in batches:
        if not batch.pdf_path:
            continue
        stored = str(batch.pdf_path).replace("\\", "/")
        filename = Path(stored).name
        if filename in moved_by_name and ("/static/pdfs/" in f"/{stored.strip('/')}" or "/pdfs/" in f"/{stored.strip('/')}"):
            batch.pdf_path = str(moved_by_name[filename])
            changed = True

    if changed:
        await session.commit()

    logger.info("Moved %s legacy PDF files to private storage.", len(moved_by_name))


@asynccontextmanager
async def lifespan(app: FastAPI):
    async with engine.begin() as conn:
        if settings.ENVIRONMENT.lower() == "production":
            # Production schema changes are applied explicitly with Alembic
            # before the service starts. Never create or mutate schema at startup.
            await conn.execute(text("SELECT 1"))
        else:
            await conn.run_sync(Base.metadata.create_all)
            await run_sqlite_migrations(conn)

    async with AsyncSessionLocal() as session:
        await migrate_legacy_public_pdfs(session)
        result = await session.execute(select(models.Admin).limit(1))
        if result.scalars().first() is None:
            hashed = auth_service.get_password_hash(settings.DASHBOARD_PASSWORD)
            session.add(models.Admin(
                username=settings.DASHBOARD_USERNAME.strip(),
                hashed_password=hashed,
                is_active=True,
            ))
            session.add(models.AuditLog(
                action="bootstrap_admin",
                performed_by="system",
                details="Created initial administrator from deployment environment",
            ))
            await session.commit()
            logger.warning("Initial SmartNet administrator created from environment configuration.")

    stop_event = asyncio.Event()
    agent_task = asyncio.create_task(subscription_agent_loop(stop_event))
    try:
        yield
    finally:
        stop_event.set()
        await agent_task


app = FastAPI(title="SmartNet API", version="1.1.0", lifespan=lifespan)

is_development = settings.ENVIRONMENT.lower() != "production"
app.add_middleware(
    CORSMiddleware,
    allow_origins=settings.CORS_ORIGINS,
    allow_origin_regex=r"^http://(localhost|127\.0\.0\.1)(:\d+)?$" if is_development else None,
    allow_credentials=True,
    allow_methods=["GET", "POST", "PUT", "PATCH", "DELETE", "OPTIONS"],
    allow_headers=["Authorization", "Content-Type", "X-Webhook-Secret", "X-Registration-Token"],
)

static_dir = Path(__file__).resolve().parent / "static"
static_dir.mkdir(parents=True, exist_ok=True)
app.mount("/static", StaticFiles(directory=str(static_dir)), name="static")

uploads_dir = Path(__file__).resolve().parent / "uploads"
cards_uploads_dir = uploads_dir / "cards"
cards_uploads_dir.mkdir(parents=True, exist_ok=True)
(uploads_dir / "receipts").mkdir(parents=True, exist_ok=True)
# Card artwork is public; payment receipts are deliberately NOT mounted publicly.
app.mount("/uploads/cards", StaticFiles(directory=str(cards_uploads_dir)), name="card-uploads")

app.include_router(auth.router)
app.include_router(mikrotik.router)
app.include_router(cards.router)
app.include_router(client.router)


